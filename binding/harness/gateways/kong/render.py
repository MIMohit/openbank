"""Kong (OSS 3.9.5, DB-less) renderer: forward-auth via the bundled
`pre-function` (serverless) plugin calling /authz/orig with lua-resty-http.

Kong OSS has no forward-auth plugin; the documented OSS route to call an external
service per request is the Serverless Functions plugin (pre-function). Running
code that `require`s resty.http and reads ngx.var.request_uri needs
untrusted_lua=on (the 3.x default `sandbox` exposes neither `ngx` nor `kong`).

Profiles:
  default      vendor defaults (route preserve_host=false, strip_path=false,
               Kong's built-in router path normalisation, merge_slashes on, and
               underscores_in_headers ON, hard-coded in Kong's nginx template).
  recommended  preserve_host=true (so the executor sees Host api.bench.test),
               headers=off, trusted_ips unset (X-Forwarded-* from clients not
               trusted), explicit underscores_in_headers off / merge_slashes on,
               bounded client body.
  strict       recommended + a pre-function deny rule over the raw path (harness
               strict deny list) and method allow-list; Kong has no native toggle.
"""
from pathlib import Path

from gateways.common import STRICT_DENY_PATH_REGEX, check, edge, write

LUA_STRICT = r"""
local raw_path = (ngx.var.request_uri or ""):match("^[^?]*")
if ngx.re.find(raw_path, [=[%(re)s]=], "joi") then
  return kong.response.exit(400, { message = "bh-strict: rejected path" })
end
local m = kong.request.get_method()
if not ({GET=1, HEAD=1, POST=1, PUT=1, DELETE=1, PATCH=1, OPTIONS=1})[m] then
  return kong.response.exit(405, { message = "bh-strict: rejected method" })
end
""" % {"re": STRICT_DENY_PATH_REGEX}

LUA_AUTHZ = r"""
local http = require "resty.http"
local hc = http.new()
hc:set_timeout(3000)
local res, err = hc:request_uri("http://verifier:9100/authz/orig", {
  method = "GET",
  headers = {
    ["X-Original-Method"] = kong.request.get_method(),
    ["X-Original-URI"] = ngx.var.request_uri,
    ["X-Original-Host"] = ngx.var.http_host,
    ["X-Original-Proto"] = kong.request.get_scheme(),
    ["Authorization"] = kong.request.get_header("authorization"),
    ["DPoP"] = kong.request.get_header("dpop"),
  },
})
if not res then
  kong.log.err("bh-authz: verifier call failed: ", err)
  return kong.response.exit(500, { message = "authz unavailable" })
end
if res.status ~= 200 then
  return kong.response.exit(401, { message = "unauthorized" },
    { ["WWW-Authenticate"] = res.headers["WWW-Authenticate"] })
end
for _, h in ipairs({ "X-Verified-Sub", "X-Verified-Jkt", "X-Verified-View" }) do
  if res.headers[h] then kong.service.request.set_header(h, res.headers[h]) end
end
"""


def _indent(code: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + line if line else "" for line in code.strip("\n").splitlines())


TEMPLATE = """# GENERATED by gateways/kong/render.py  profile={profile} placement={placement}
_format_version: "3.0"
services:
- name: executor
  url: http://executor:8080
  routes:
  - name: api
    paths: ["/api/"]
    strip_path: false
    preserve_host: {preserve_host}
{plugins}"""


def render(profile: str, placement: str, outdir: Path) -> dict:
    check(profile, placement)
    code = ""
    if profile == "strict":
        code += LUA_STRICT
    if edge(placement):
        code += LUA_AUTHZ
    plugins = ""
    if code:
        plugins = "    plugins:\n    - name: pre-function\n      config:\n        access:\n        - |\n" + _indent(code, 10) + "\n"
    write(outdir / "kong.yml", TEMPLATE.format(
        profile=profile, placement=placement,
        preserve_host="false" if profile == "default" else "true", plugins=plugins))
    env = {
        "KONG_DATABASE": "off",
        "KONG_DECLARATIVE_CONFIG": "/kong/kong.yml",
        "KONG_PROXY_LISTEN": "0.0.0.0:8000",
        "KONG_ADMIN_LISTEN": "127.0.0.1:8001",
        "KONG_PROXY_ACCESS_LOG": "/dev/stdout",
        "KONG_PROXY_ERROR_LOG": "/dev/stderr",
        "KONG_ADMIN_ACCESS_LOG": "off",
        "KONG_NGINX_WORKER_PROCESSES": "1",
        "KONG_UNTRUSTED_LUA": "on",
    }
    if profile != "default":
        env.update({
            "KONG_HEADERS": "off",
            # Kong's nginx_kong.lua template hard-codes `underscores_in_headers on;` in the http
            # block, so the override must go in the proxy server block (server-level directive).
            "KONG_NGINX_PROXY_UNDERSCORES_IN_HEADERS": "off",
            "KONG_NGINX_PROXY_MERGE_SLASHES": "on",
            "KONG_NGINX_HTTP_CLIENT_MAX_BODY_SIZE": "1m",
        })
    return {"volumes": ["./gateway/kong.yml:/kong/kong.yml:ro"], "environment": env}
