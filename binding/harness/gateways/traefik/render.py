"""Traefik renderer: file provider + ForwardAuth middleware -> /authz/fwd.

Profiles (entryPoint http options, Traefik v3.7 reference):
  default      vendor defaults: sanitizePath true, all encodedCharacters.allow* true,
               aliasHeadersStrategy keep, forwardedHeaders not trusted.
  recommended  docs guidance: keep sanitizePath true ("setting it to false is not
               safe"); disallow encoded characters that create split views with
               non-RFC-3986 backends (slash, backslash, NUL, semicolon); explicit
               trustForwardHeader false; bounded ForwardAuth body sizes.
  strict       all seven encodedCharacters.allow* false, aliasHeadersStrategy reject.
"""
from pathlib import Path

from gateways.common import check, edge, write

ENC = ["allowEncodedSlash", "allowEncodedBackSlash", "allowEncodedNullCharacter",
       "allowEncodedSemicolon", "allowEncodedPercent", "allowEncodedQuestionMark",
       "allowEncodedHash"]

PROFILE_EP = {
    "default": "",
    "recommended": """
    http:
      sanitizePath: true
      encodedCharacters:
        allowEncodedSlash: false
        allowEncodedBackSlash: false
        allowEncodedNullCharacter: false
        allowEncodedSemicolon: false""",
    "strict": """
    http:
      sanitizePath: true
      aliasHeadersStrategy: reject
      encodedCharacters:
""" + "\n".join(f"        {k}: false" for k in ENC),
}

STATIC = """# GENERATED by gateways/traefik/render.py  profile={profile} placement={placement}
entryPoints:
  web:
    address: ":8000"{ep}
providers:
  file:
    filename: /etc/traefik/dynamic.yml
    watch: false
log:
  level: INFO
accessLog: {{}}
ping:
  entryPoint: web
"""

FWD = {
    "default": """
    bh-authz:
      forwardAuth:
        address: "http://verifier:9100/authz/fwd"
        authRequestHeaders: ["Authorization", "DPoP"]
        authResponseHeadersRegex: "^X-Verified-"
""",
    "recommended": """
    bh-authz:
      forwardAuth:
        address: "http://verifier:9100/authz/fwd"
        trustForwardHeader: false
        authRequestHeaders: ["Authorization", "DPoP"]
        authResponseHeadersRegex: "^X-Verified-"
        maxBodySize: 1048576
        maxResponseBodySize: 65536
""",
}
FWD["strict"] = FWD["recommended"]

DYNAMIC = """# GENERATED by gateways/traefik/render.py  profile={profile} placement={placement}
http:
  routers:
    api:
      entryPoints: [web]
      rule: "PathPrefix(`/api/`)"
      service: executor{mw}
  services:
    executor:
      loadBalancer:
        passHostHeader: true
        servers:
        - url: "http://executor:8080"
{middlewares}"""


def render(profile: str, placement: str, outdir: Path) -> dict:
    check(profile, placement)
    e = edge(placement)
    write(outdir / "traefik.yml", STATIC.format(profile=profile, placement=placement, ep=PROFILE_EP[profile]))
    write(outdir / "dynamic.yml", DYNAMIC.format(
        profile=profile, placement=placement,
        mw="\n      middlewares: [bh-authz]" if e else "",
        middlewares=("  middlewares:" + FWD[profile]) if e else ""))
    return {
        "volumes": ["./gateway/traefik.yml:/etc/traefik/traefik.yml:ro",
                    "./gateway/dynamic.yml:/etc/traefik/dynamic.yml:ro"],
        "command": ["traefik", "--configFile=/etc/traefik/traefik.yml"],
    }
