"""NGINX renderer: auth_request subrequest -> /authz/orig.

Profiles:
  default      vendor defaults (merge_slashes on, ignore_invalid_headers on,
               underscores_in_headers off; proxy_pass without URI part so the
               client's request URI is passed unchanged).
  recommended  NGINX admin guide / module docs guidance: auth_request pattern
               from the docs (X-Original-URI $request_uri), body not sent to the
               auth service, server_tokens off, explicit merge_slashes on,
               underscores_in_headers off, ignore_invalid_headers on, proxy
               headers overwritten (Host, X-Forwarded-For/Proto), HTTP/1.1 upstream.
  strict       recommended + native `if`/`return 400` rejection of raw targets
               matching the harness strict deny list (encoded / , \\ , NUL, ;, %,
               ?, #, ., raw dot-segments, empty segments) and of method tokens
               outside RFC 9110 + PATCH. NGINX has no built-in toggle for these.
"""
from pathlib import Path

from gateways.common import STRICT_DENY_PATH_REGEX, check, edge, write

AUTH_LOC = """
        location = /_bh_authz {
            internal;
            proxy_pass http://verifier:9100/authz/orig;
            proxy_pass_request_body off;
            proxy_set_header Content-Length "";
            proxy_set_header X-Original-Method $request_method;
            proxy_set_header X-Original-URI $request_uri;
            proxy_set_header X-Original-Host $host;
            proxy_set_header X-Original-Proto $scheme;
        }
"""

API_EDGE = """
            auth_request /_bh_authz;
            auth_request_set $bh_sub $upstream_http_x_verified_sub;
            auth_request_set $bh_jkt $upstream_http_x_verified_jkt;
            auth_request_set $bh_view $upstream_http_x_verified_view;
            proxy_set_header X-Verified-Sub $bh_sub;
            proxy_set_header X-Verified-Jkt $bh_jkt;
            proxy_set_header X-Verified-View $bh_view;"""

HTTP_PROFILE = {
    "default": "",
    "recommended": """
    server_tokens off;
    merge_slashes on;
    underscores_in_headers off;
    ignore_invalid_headers on;
    client_max_body_size 1m;""",
}
HTTP_PROFILE["strict"] = HTTP_PROFILE["recommended"]

PROXY_PROFILE = {
    "default": "",
    "recommended": """
            proxy_http_version 1.1;
            proxy_set_header Connection "";
            proxy_set_header Host $host;
            proxy_set_header X-Forwarded-For $remote_addr;
            proxy_set_header X-Forwarded-Proto $scheme;""",
}
PROXY_PROFILE["strict"] = PROXY_PROFILE["recommended"]

STRICT_SERVER = r"""
        # strict: harness deny list over the raw path (no native toggle in NGINX)
        set $bh_raw_path $request_uri;
        if ($request_uri ~ "^([^?]*)") { set $bh_raw_path $1; }
        if ($bh_raw_path ~* "%(regex)s") { return 400; }
        if ($request_method !~ "^(GET|HEAD|POST|PUT|DELETE|PATCH|OPTIONS)$") { return 405; }
""" % {"regex": STRICT_DENY_PATH_REGEX.replace("\\", "\\\\")}

TEMPLATE = """# GENERATED by gateways/nginx/render.py  profile={profile} placement={placement}
worker_processes 1;
error_log /dev/stderr info;
events {{ worker_connections 1024; }}
http {{
    access_log /dev/stdout;
    resolver 127.0.0.11 valid=10s ipv6=off;{http_profile}
    server {{
        listen 8000;
        server_name _;{strict}
        location /api/ {{{edge}{proxy}
            proxy_pass http://executor:8080;
        }}
{auth}    }}
}}
"""


def render(profile: str, placement: str, outdir: Path) -> dict:
    check(profile, placement)
    e = edge(placement)
    write(outdir / "nginx.conf", TEMPLATE.format(
        profile=profile, placement=placement, http_profile=HTTP_PROFILE[profile],
        strict=STRICT_SERVER if profile == "strict" else "",
        edge=API_EDGE if e else "", proxy=PROXY_PROFILE[profile], auth=AUTH_LOC if e else ""))
    return {
        "volumes": ["./gateway/nginx.conf:/etc/nginx/nginx.conf:ro"],
        "command": ["nginx", "-g", "daemon off;"],
    }
