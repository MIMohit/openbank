"""HAProxy renderer: Lua action (core.httpclient) calling /authz/orig.

HAProxy has no built-in forward-auth; the documented extension points are Lua
actions and SPOE. We use a Lua `http-req` action (bh_authz.lua) that copies the
request view into X-Original-* and passes Authorization and DPoP.

Profiles:
  default      vendor defaults (no URI normalisation, header names preserved).
  recommended  `http-request normalize-uri` normalisers documented in the
               configuration manual (path-strip-dotdot, path-merge-slashes,
               percent-decode-unreserved, percent-to-uppercase, fragment-strip),
               applied BEFORE the authz action so verifier and backend see the
               same URI; `option http-restrict-req-hdr-names delete`.
  strict       raw-path deny rule (harness strict deny list) and method
               allow-list evaluated first, then the normalisers in their `strict`
               / `full` variants, and `http-restrict-req-hdr-names reject`.
"""
from pathlib import Path

from gateways.common import STRICT_DENY_PATH_REGEX, check, edge, write

LUA = r"""-- GENERATED by gateways/haproxy/render.py: forward-auth to /authz/orig
local function first(v)
  if v == nil then return nil end
  if type(v) == "table" then return v[0] or v[1] end
  return v
end

core.register_action("bh_authz", { "http-req" }, function(txn)
  local hdrs = {
    ["X-Original-Method"] = { txn.f:method() },
    ["X-Original-URI"] = { txn.f:url() },
    ["X-Original-Host"] = { txn.f:req_fhdr("host") or "" },
    ["X-Original-Proto"] = { "http" },
  }
  local a = txn.f:req_fhdr("authorization")
  if a ~= nil then hdrs["Authorization"] = { a } end
  local d = txn.f:req_fhdr("dpop")
  if d ~= nil then hdrs["DPoP"] = { d } end
  local hc = core.httpclient()
  local res = hc:get({ url = "http://verifier:9100/authz/orig", headers = hdrs, timeout = 3000 })
  if res == nil or res.status == nil then
    txn:set_var("txn.bh_authz", "error")
    return
  end
  if res.status == 200 then
    txn:set_var("txn.bh_authz", "allow")
    for _, h in ipairs({ "x-verified-sub", "x-verified-jkt", "x-verified-view" }) do
      local v = first(res.headers and res.headers[h])
      if v ~= nil then txn.http:req_set_header(h, v) end
    end
  else
    txn:set_var("txn.bh_authz", "deny")
  end
end)
"""

PROFILE_FE = {
    "default": "",
    "recommended": """
    option http-restrict-req-hdr-names delete
    http-request normalize-uri fragment-strip
    http-request normalize-uri path-strip-dotdot
    http-request normalize-uri path-merge-slashes
    http-request normalize-uri percent-decode-unreserved
    http-request normalize-uri percent-to-uppercase""",
    "strict": """
    option http-restrict-req-hdr-names reject
    http-request deny deny_status 405 unless { method GET HEAD POST PUT DELETE PATCH OPTIONS }
    http-request deny deny_status 400 if { path -m reg -i '%s' }
    http-request normalize-uri fragment-strip
    http-request normalize-uri path-strip-dotdot full
    http-request normalize-uri path-merge-slashes
    http-request normalize-uri percent-decode-unreserved strict
    http-request normalize-uri percent-to-uppercase strict""" % STRICT_DENY_PATH_REGEX,
}

EDGE_FE = """
    http-request lua.bh_authz if is_api
    http-request return status 500 content-type application/json string '{"error":"authz unavailable"}' if is_api { var(txn.bh_authz) -m str error }
    http-request return status 401 content-type application/json string '{"error":"unauthorized"}' if is_api !{ var(txn.bh_authz) -m str allow }"""

TEMPLATE = """# GENERATED by gateways/haproxy/render.py  profile={profile} placement={placement}
global
    log stdout format raw local0 info{lua_load}{experimental}

defaults
    mode http
    log global
    option httplog
    timeout connect 3s
    timeout client 30s
    timeout server 30s

resolvers docker
    nameserver dns1 127.0.0.11:53
    hold valid 10s

frontend fe
    bind :8000
    acl is_api path_beg /api/{profile_fe}{edge_fe}
    http-request return status 404 content-type application/json string '{{"error":"not found"}}' unless is_api
    default_backend be_exec

backend be_exec
    server exec executor:8080 resolvers docker init-addr last,libc,none
"""


def render(profile: str, placement: str, outdir: Path) -> dict:
    check(profile, placement)
    e = edge(placement)
    write(outdir / "haproxy.cfg", TEMPLATE.format(
        profile=profile, placement=placement,
        lua_load="\n    tune.lua.bool-sample-conversion normal\n    lua-load /usr/local/etc/haproxy/bh_authz.lua" if e else "",
        # normalize-uri is still flagged experimental in HAProxy 3.2
        experimental="\n    expose-experimental-directives" if profile != "default" else "",
        profile_fe=PROFILE_FE[profile], edge_fe=EDGE_FE if e else ""))
    vols = ["./gateway/haproxy.cfg:/usr/local/etc/haproxy/haproxy.cfg:ro"]
    if e:
        write(outdir / "bh_authz.lua", LUA)
        vols.append("./gateway/bh_authz.lua:/usr/local/etc/haproxy/bh_authz.lua:ro")
    return {"volumes": vols}
