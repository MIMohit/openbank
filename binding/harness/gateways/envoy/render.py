"""Envoy renderer: HCM + ext_authz HTTP service (path_prefix /authz/envoy).

Profiles (HttpConnectionManager fields):
  default      vendor defaults (no normalize_path, no merge_slashes,
               path_with_escaped_slashes_action unset = KEEP_UNCHANGED,
               headers_with_underscores_action unset = ALLOW).
  recommended  Envoy edge-proxy best practices + path normalisation guidance:
               normalize_path, merge_slashes, UNESCAPE_AND_REDIRECT,
               headers_with_underscores_action REJECT_REQUEST, use_remote_address.
  strict       as recommended but path_with_escaped_slashes_action REJECT_REQUEST,
               plus strip_any_host_port.
"""
from pathlib import Path

from gateways.common import check, edge, write

PROFILE_HCM = {
    "default": "",
    "recommended": """
          normalize_path: true
          merge_slashes: true
          path_with_escaped_slashes_action: UNESCAPE_AND_REDIRECT
          use_remote_address: true
          common_http_protocol_options:
            headers_with_underscores_action: REJECT_REQUEST
            idle_timeout: 3600s
          request_headers_timeout: 10s""",
    "strict": """
          normalize_path: true
          merge_slashes: true
          path_with_escaped_slashes_action: REJECT_REQUEST
          use_remote_address: true
          strip_any_host_port: true
          common_http_protocol_options:
            headers_with_underscores_action: REJECT_REQUEST
            idle_timeout: 3600s
          request_headers_timeout: 10s""",
}

EXT_AUTHZ = """
          - name: envoy.filters.http.ext_authz
            typed_config:
              "@type": type.googleapis.com/envoy.extensions.filters.http.ext_authz.v3.ExtAuthz
              transport_api_version: V3
              failure_mode_allow: false
              allowed_headers:
                patterns:
                - {exact: authorization, ignore_case: true}
                - {exact: dpop, ignore_case: true}
              http_service:
                server_uri: {uri: "http://verifier:9100", cluster: verifier, timeout: 3s}
                path_prefix: /authz/envoy
                authorization_response:
                  allowed_upstream_headers:
                    patterns:
                    - {prefix: x-verified-, ignore_case: true}
                  allowed_client_headers:
                    patterns:
                    - {exact: www-authenticate, ignore_case: true}"""

VERIFIER_CLUSTER = """
  - name: verifier
    type: STRICT_DNS
    connect_timeout: 2s
    load_assignment:
      cluster_name: verifier
      endpoints:
      - lb_endpoints:
        - endpoint: {address: {socket_address: {address: verifier, port_value: 9100}}}"""

TEMPLATE = """# GENERATED by gateways/envoy/render.py  profile={profile} placement={placement}
admin:
  address: {{socket_address: {{address: 127.0.0.1, port_value: 9901}}}}
static_resources:
  listeners:
  - name: main
    address: {{socket_address: {{address: 0.0.0.0, port_value: 8000}}}}
    filter_chains:
    - filters:
      - name: envoy.filters.network.http_connection_manager
        typed_config:
          "@type": type.googleapis.com/envoy.extensions.filters.network.http_connection_manager.v3.HttpConnectionManager
          stat_prefix: ingress
          codec_type: AUTO{hcm}
          route_config:
            name: local
            virtual_hosts:
            - name: api
              domains: ["*"]
              routes:
              - match: {{prefix: "/api/"}}
                route: {{cluster: executor, timeout: 10s}}
          http_filters:{ext_authz}
          - name: envoy.filters.http.router
            typed_config:
              "@type": type.googleapis.com/envoy.extensions.filters.http.router.v3.Router
  clusters:
  - name: executor
    type: STRICT_DNS
    connect_timeout: 2s
    load_assignment:
      cluster_name: executor
      endpoints:
      - lb_endpoints:
        - endpoint: {{address: {{socket_address: {{address: executor, port_value: 8080}}}}}}{verifier_cluster}
"""


def render(profile: str, placement: str, outdir: Path) -> dict:
    check(profile, placement)
    e = edge(placement)
    write(outdir / "envoy.yaml", TEMPLATE.format(
        profile=profile, placement=placement, hcm=PROFILE_HCM[profile],
        ext_authz=EXT_AUTHZ if e else "", verifier_cluster=VERIFIER_CLUSTER if e else ""))
    return {
        "volumes": ["./gateway/envoy.yaml:/etc/envoy/envoy.yaml:ro"],
        "command": ["envoy", "-c", "/etc/envoy/envoy.yaml", "--log-level", "info"],
    }
