"""Apache APISIX renderer (standalone / YAML config provider): forward-auth
plugin -> /authz/fwd.

Note (from apisix/init.lua and plugins/forward-auth.lua in the pinned image):
APISIX overwrites ctx.var.request_uri with its normalised uri before plugins run,
and forward-auth sends X-Forwarded-Uri = ctx.var.request_uri, so the verifier
sees APISIX's normalised view, and the same normalised uri is sent upstream.

Profiles (apisix.* / nginx_config.* keys in config.yaml):
  default      vendor defaults (underscores_in_headers on, normalize_uri_like_servlet
               false, delete_uri_tail_slash false, match_uri_encoded_slash false).
  recommended  underscores_in_headers off, server tokens off, bounded body size,
               forward-auth over GET with only Authorization + DPoP.
  strict       recommended + normalize_uri_like_servlet true + a
               serverless-pre-function deny rule over the raw request path
               (harness strict deny list) and method allow-list.
"""
import json
from pathlib import Path

from gateways.common import STRICT_DENY_PATH_REGEX, check, edge, write

CONFIG = """# GENERATED by gateways/apisix/render.py  profile={profile} placement={placement}
deployment:
  role: data_plane
  role_data_plane:
    config_provider: yaml
apisix:
  node_listen: 8000
  enable_admin: false
  enable_control: false{apisix_extra}
nginx_config:
  error_log: /dev/stderr
  error_log_level: warn
  worker_processes: 1
  http:
    enable_access_log: true
    access_log: /dev/stdout{http_extra}
"""

PROFILE_APISIX = {
    "default": "",
    "recommended": "\n  enable_server_tokens: false",
    "strict": "\n  enable_server_tokens: false\n  normalize_uri_like_servlet: true",
}
PROFILE_HTTP = {
    "default": "",
    "recommended": '\n    underscores_in_headers: "off"\n    client_max_body_size: 1m',
}
PROFILE_HTTP["strict"] = PROFILE_HTTP["recommended"]

STRICT_FN = r"""return function(conf, ctx)
  local raw_path = (ngx.var.request_uri or ""):match("^[^?]*")
  if ngx.re.find(raw_path, [=[%(re)s]=], "joi") then
    return 400, { message = "bh-strict: rejected path" }
  end
  local m = ngx.req.get_method()
  if not ({GET=1, HEAD=1, POST=1, PUT=1, DELETE=1, PATCH=1, OPTIONS=1})[m] then
    return 405, { message = "bh-strict: rejected method" }
  end
end""" % {"re": STRICT_DENY_PATH_REGEX}


def render(profile: str, placement: str, outdir: Path) -> dict:
    check(profile, placement)
    route = {
        "id": "api",
        "uri": "/api/*",
        "upstream": {"type": "roundrobin", "pass_host": "pass", "nodes": {"executor:8080": 1}},
    }
    plugins = {}
    if profile == "strict":
        plugins["serverless-pre-function"] = {"phase": "rewrite", "functions": [STRICT_FN]}
    if edge(placement):
        plugins["forward-auth"] = {
            "uri": "http://verifier:9100/authz/fwd",
            "request_method": "GET",
            "request_headers": ["Authorization", "DPoP"],
            "upstream_headers": ["X-Verified-Sub", "X-Verified-Jkt", "X-Verified-View"],
            "client_headers": ["WWW-Authenticate"],
            "timeout": 3000,
        }
    if plugins:
        route["plugins"] = plugins
    # JSON is valid YAML; avoids a PyYAML dependency for the gateway package.
    write(outdir / "apisix.yaml",
          f"# GENERATED by gateways/apisix/render.py  profile={profile} placement={placement}\n"
          + "routes:\n  - " + json.dumps(route, indent=2).replace("\n", "\n    ") + "\n#END\n")
    write(outdir / "config.yaml", CONFIG.format(
        profile=profile, placement=placement,
        apisix_extra=PROFILE_APISIX[profile], http_extra=PROFILE_HTTP[profile]))
    return {
        "volumes": ["./gateway/config.yaml:/usr/local/apisix/conf/config.yaml:ro",
                    "./gateway/apisix.yaml:/usr/local/apisix/conf/apisix.yaml:ro"],
        "environment": {"APISIX_STAND_ALONE": "true"},
    }
