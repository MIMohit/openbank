"""Generate harness/orchestrator/generated/<id>/docker-compose.yml from a topology."""
import importlib
import json
import os
import shutil
import subprocess
from pathlib import Path

import yaml

from orchestrator.topology import HARNESS, STUB

ORCH = HARNESS / "orchestrator"
GENERATED = ORCH / "generated"
LOGS = HARNESS / "logs"
STUB_PY_IMAGE = "python:3.12.16-slim-trixie"
MEM = {"gateway": "512m", "verifier": "256m", "executor": "640m", "probe": "64m"}


def project_name(tid: str) -> str:
    # CONTRACT: bh-<id>. BH_PROJECT_PREFIX lets a worker prefix its tag (e.g. w6-bh-).
    return os.environ.get("BH_PROJECT_PREFIX", "bh-") + tid


def image_present(image: str) -> bool:
    return subprocess.run(["docker", "image", "inspect", image], capture_output=True).returncode == 0


def resolve_stubs(t: dict, stubs: str) -> dict:
    """stubs: auto (stub only when the real image is absent locally) | on | off."""
    out = {}
    for role, image in (("verifier", t["verifier"]["image"]), ("executor", t["executor_image"])):
        if image == STUB or stubs == "on":
            out[role] = True
        elif stubs == "off":
            out[role] = False
        else:
            out[role] = not image_present(image)
    return out


def _abs_volumes(vols, base: Path):
    res = []
    for v in vols:
        src, rest = v.split(":", 1)
        if src.startswith("./"):
            src = str((base / src[2:]).resolve())
        res.append(f"{src}:{rest}")
    return res


def generate(t: dict, stubs: str = "auto") -> tuple[Path, dict]:
    tid = t["id"]
    gdir = GENERATED / tid
    shutil.rmtree(gdir, ignore_errors=True)
    (gdir / "gateway").mkdir(parents=True)
    logdir = LOGS / tid
    logdir.mkdir(parents=True, exist_ok=True)

    gw = importlib.import_module(f"gateways.{t['gateway']}.render")
    gsvc = gw.render(t["profile"], t["placement"], gdir / "gateway")
    use_stub = resolve_stubs(t, stubs)

    gateway = {
        "image": t["gateway_image"],
        "ports": [f"127.0.0.1:{t['host_port']}:8000"],
        "depends_on": ["executor", "verifier"],
        "mem_limit": MEM["gateway"],
        "volumes": _abs_volumes(gsvc.get("volumes", []), gdir),
    }
    for k in ("command", "environment", "entrypoint"):
        if k in gsvc:
            gateway[k] = gsvc[k]

    v = t["verifier"]
    venv = {"HTU_CANON": v["canon"], "JTI_CACHE": v["jti_cache"], "IAT_WINDOW": str(v["iat_window"]),
            "VIEW_MAC": v["view_mac"], "VIEW_MAC_KEY": v["view_mac_key"],
            "AS_PUB_JWK": "/keys/as_pub.jwk", "LOG_PATH": "/logs/verifier.jsonl"}
    vvols = [f"{logdir}:/logs", f"{HARNESS / 'keys'}:/keys:ro"]
    if use_stub["verifier"]:
        verifier = {"image": STUB_PY_IMAGE, "command": ["python", "-u", "/stub/stub_verifier.py"],
                    "volumes": vvols + [f"{ORCH / 'stub_verifier'}:/stub:ro"],
                    "labels": {"bh.stub": "verifier"}}
    else:
        verifier = {"image": v["image"], "volumes": vvols}
    verifier.update({"environment": venv, "mem_limit": MEM["verifier"]})

    eenv = {"OVERRIDE": t["override"], "VERIFY_MODE": t["verify_mode"],
            "FRAMEWORK_TAG": t["framework"], "LOG_PATH": "/logs/executor.jsonl"}
    if use_stub["executor"]:
        executor = {"image": STUB_PY_IMAGE, "command": ["python", "-u", "/stub/stub_executor.py"],
                    "volumes": [f"{logdir}:/logs", f"{ORCH / 'stub_executor'}:/stub:ro"],
                    "labels": {"bh.stub": "executor"}}
    else:
        executor = {"image": t["executor_image"], "volumes": [f"{logdir}:/logs"]}
    executor.update({"environment": eenv, "mem_limit": MEM["executor"]})

    probe = {
        "image": STUB_PY_IMAGE,
        "command": ["sleep", "infinity"],
        "init": True,
        "volumes": [f"{ORCH / 'probe'}:/probe:ro"],
        "mem_limit": MEM["probe"],
        "depends_on": ["gateway"],
        "healthcheck": {"test": ["CMD", "python", "/probe/probe.py"],
                        "interval": "2s", "timeout": "5s", "retries": 120, "start_period": "2s"},
    }
    compose = {"name": project_name(tid),
               "services": {"gateway": gateway, "verifier": verifier, "executor": executor, "probe": probe}}
    (gdir / "docker-compose.yml").write_text(
        f"# GENERATED by orchestrator/compose.py from topology {tid}; do not edit\n"
        + yaml.safe_dump(compose, sort_keys=False))
    meta = {"topology": t, "stubs": use_stub, "project": project_name(tid)}
    (gdir / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    return gdir / "docker-compose.yml", meta
