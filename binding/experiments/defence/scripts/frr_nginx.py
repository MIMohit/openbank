"""Inject the legitimate rewrite scenarios into an orchestrator-generated nginx.conf (in place).
The /api/ location of the rendered profile (default or strict; edge or origin) is copied verbatim
into /svc/ (strip prefix) and /api/latest/ (version rewrite) locations with one `rewrite ... break`
line each; the /api/ location gets a trailing-slash strip; `http2 on;` enables h2c (prior knowledge)
on the same listener. Nothing else in the rendered config changes.  Usage: frr_nginx.py <nginx.conf>"""
import re, sys
p = sys.argv[1]; s = open(p).read()
i = s.index("location /api/ {"); j = s.index("{", i); depth, k = 0, j
while True:
    depth += {"{": 1, "}": -1}.get(s[k], 0)
    if depth == 0: break
    k += 1
body = s[j + 1:k]
ind = " " * (len(s[:i]) - len(s[:i].rstrip(" ")))
extra = (f"location /svc/ {{\n{ind}    rewrite ^/svc(/.*)$ $1 break;{body}}}\n\n{ind}"
         f"location /api/latest/ {{\n{ind}    rewrite ^/api/latest/(.*)$ /api/v1/$1 break;{body}}}\n\n{ind}")
new_api = f"location /api/ {{\n{ind}    rewrite ^(/api/.+)/$ $1 break;{body}}}"
s = s[:i] + extra + new_api + s[k + 1:]
s = re.sub(r"(listen 8000[^;]*;)", r"\1\n" + ind + "http2 on;", s, count=1)
s = s.replace("# GENERATED by", "# W17 FRR: rewrite scenarios injected by experiments/defence/scripts/frr_nginx.py into a config GENERATED by", 1)
open(p, "w").write(s)
