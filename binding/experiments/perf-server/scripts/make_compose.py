"""Render the 8 perf topologies (B-edge, B-origin, D-A, D-B x fastapi, spring) as self-contained compose files for the
remote server. Same topology definitions as experiments/defence/topologies/perf/*.yaml (loaded with the harness loader,
nginx config rendered by harness/gateways/nginx/render.py), with the server safety changes:
  * images renamed to the locally cross-built linux/amd64 bhperf-* tags;
  * NO published ports, NO probe sidecar; all services on the external network bhperf-net;
  * container names bhperf-<role>, label bhperf=1, restart "no", json-file logs max-size 10m;
  * CPU / memory caps (deploy.resources.limits): gateway 0.2/64M, verifier 0.3/256M, executor 0.3/640M
    (the k6 container, 0.2/256M, is started by run_topology.sh) -> total 1.0 CPU, 1216 MiB;
  * host paths under /root/bhperf/.
Writes compose/<cfg>-<fw>/{docker-compose.yml,nginx.conf,topology.yaml}.
Run: python3 scripts/make_compose.py  (from experiments/perf-server; needs PyYAML)."""
import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent.parent
B = HERE.parent.parent
sys.path.insert(0, str(B / "harness"))
from orchestrator.topology import load  # noqa: E402
from gateways.nginx import render as nginx_render  # noqa: E402

SRV = "/root/bhperf"
IMG = {"bh-verifier:latest": "bhperf-verifier:amd64",
       "bh-exec-fastapi:v2": "bhperf-exec-fastapi:amd64-v2", "bh-exec-fastapi:defence": "bhperf-exec-fastapi:amd64-def",
       "bh-exec-spring:v2": "bhperf-exec-spring:amd64-v2", "bh-exec-spring:defence": "bhperf-exec-spring:amd64-def",
       "nginx:1.30.7-alpine": "bhperf-nginx:amd64"}
CAPS = {"gateway": ("0.2", "64M"), "verifier": ("0.3", "256M"), "executor": ("0.3", "640M")}
LOGGING = {"driver": "json-file", "options": {"max-size": "10m", "max-file": "1"}}


def svc(role, image, **kw):
    cpu, mem = CAPS[role]
    s = {"image": image, "container_name": f"bhperf-{role}", "labels": {"bhperf": "1"}, "restart": "no",
         "logging": LOGGING, "networks": ["bhperf-net"],
         "deploy": {"resources": {"limits": {"cpus": cpu, "memory": mem}}}}
    s.update(kw)
    return s


def main():
    src = B / "experiments" / "defence" / "topologies" / "perf"
    for cfg in ("bedge", "borigin", "da", "db"):
        for fw in ("fastapi", "spring"):
            t = load(src / f"w17-perf-{cfg}-{fw}.yaml")
            name = f"{cfg}-{fw}"
            out = HERE / "compose" / name
            out.mkdir(parents=True, exist_ok=True)
            g = nginx_render.render(t["profile"], t["placement"], out)  # writes out/nginx.conf
            assert g["volumes"] == ["./gateway/nginx.conf:/etc/nginx/nginx.conf:ro"], g
            v = t["verifier"]
            venv = {"HTU_CANON": v["canon"], "JTI_CACHE": v["jti_cache"], "IAT_WINDOW": str(v["iat_window"]),
                    "VIEW_MAC": v["view_mac"], "VIEW_MAC_KEY": v["view_mac_key"],
                    "AS_PUB_JWK": "/keys/as_pub.jwk", "LOG_PATH": "/logs/verifier.jsonl"}
            eenv = {"OVERRIDE": t["override"], "VERIFY_MODE": t["verify_mode"],
                    "FRAMEWORK_TAG": t["framework"], "LOG_PATH": "/logs/executor.jsonl"}
            logs = f"{SRV}/logs/{name}"
            compose = {
                "name": f"bhperf-{name}",
                "services": {
                    "gateway": svc("gateway", IMG[t["gateway_image"]], depends_on=["executor", "verifier"],
                                   volumes=[f"{SRV}/compose/{name}/nginx.conf:/etc/nginx/nginx.conf:ro"],
                                   command=g["command"]),
                    "verifier": svc("verifier", IMG[v["image"]], environment=venv,
                                    volumes=[f"{logs}:/logs", f"{SRV}/keys:/keys:ro"]),
                    "executor": svc("executor", IMG[t["executor_image"]], environment=eenv,
                                    volumes=[f"{logs}:/logs"]),
                },
                "networks": {"bhperf-net": {"external": True}},
            }
            (out / "docker-compose.yml").write_text(
                f"# GENERATED by perf-server/scripts/make_compose.py from defence/topologies/perf/w17-perf-{name}.yaml\n"
                + yaml.safe_dump(compose, sort_keys=False))
            (out / "topology.yaml").write_text(yaml.safe_dump(t, sort_keys=False))
            print(name, t["profile"], t["placement"], t["verify_mode"], t["executor_image"], "view_mac=" + v["view_mac"])


if __name__ == "__main__":
    main()
