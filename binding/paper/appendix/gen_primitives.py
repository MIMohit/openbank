"""Generate appendix/primitives_table.tex from harness/mutator/primitives/{g1,g2,g3}.yaml.
Run from binding/paper:  python appendix/gen_primitives.py
Counts every primitive by (class group, family = `class` field); lists ids and the first source."""
import collections, pathlib, re, yaml
root = pathlib.Path(__file__).resolve().parents[2] / "harness" / "mutator" / "primitives"
def tex(s):
    s = str(s)
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")]:
        s = s.replace(a, b)
    return s
rows, totals = [], {}
for g in ("g1", "g2", "g3"):
    d = yaml.safe_load((root / f"{g}.yaml").read_text())
    fam = collections.OrderedDict()
    for p in d["primitives"]:
        fam.setdefault(p["class"], []).append(p)
    totals[g] = len(d["primitives"])
    for name, ps in fam.items():
        src = re.split(r"[;(]", ps[0].get("source", ""))[0].strip()
        rows.append((g.upper(), name, len(ps), src))
out = [r"% GENERATED by appendix/gen_primitives.py from harness/mutator/primitives/*.yaml -- do not edit.",
       r"\begin{table*}[h]",
       r"\caption{Mutation primitive catalogue by class and family (generated from the catalogue files; "
       + f"G1 {totals['g1']}, G2 {totals['g2']}, G3 {totals['g3']} primitives).}}\\label{{tab:prims}}",
       r"\scriptsize\begin{tabular}{@{}l l r p{11.5cm}@{}}",
       r"\toprule Class & Family & $n$ & Example source (first primitive of the family) \\ \midrule"]
for g, name, n, src in rows:
    out.append(f"{g} & {tex(name)} & {n} & {tex(src)} \\\\")
out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
(pathlib.Path(__file__).parent / "primitives_table.tex").write_text("\n".join(out) + "\n")
print(totals, len(rows), "families")
